"""Runs the evaluations, writes eval/results/*.json and a Markdown summary of the current numbers."""

from __future__ import annotations

import json
import time

from .. import paths
from ..sim.faults import FAULT_KINDS

RESULTS = paths.EVAL / "results"


def _save(name: str, data: dict) -> None:
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / f"{name}.json").write_text(json.dumps(data, indent=1), encoding="utf-8")


def _load(name: str) -> dict | None:
    p = RESULTS / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def run(
    which: str, use_llm: bool = False, offline: bool = False, quick: bool = False, embeddings: bool = False
) -> None:
    if which in ("detection", "all"):
        from . import detection

        t0 = time.time()
        if quick:
            out = {"heldout": detection.evaluate(detection.HELDOUT_SEEDS[:3])}
        else:
            out = {
                "tune": detection.evaluate(detection.TUNE_SEEDS),
                "heldout": detection.evaluate(detection.HELDOUT_SEEDS),
            }
        out["seconds"] = round(time.time() - t0, 1)
        if not quick:
            _save("detection", out)
        print_detection(out)
    if which in ("dosing", "all"):
        from . import dosing

        out = {"tune": dosing.evaluate(dosing.TUNE_SEEDS), "heldout": dosing.evaluate(dosing.HELDOUT_SEEDS)}
        _save("dosing", out)
        print_dosing(out)
    if which in ("assistant", "all"):
        from . import assistant

        out = {"retrieval_only": assistant.evaluate(use_llm=False)}
        if embeddings:
            out["retrieval_hybrid"] = assistant.evaluate(use_llm=False, offline=offline, embeddings=True)
        if use_llm:
            out["llm_guards"] = assistant.evaluate(use_llm=True, offline=offline)
        prev = _load("assistant") or {}
        for k in ("llm_guards", "retrieval_hybrid"):  # keep earlier live results when this run skips them
            if k not in out and k in prev:
                out[k] = prev[k]
        _save("assistant", out)
        print_assistant(out)
    write_summary()


def print_detection(out: dict) -> None:
    for split in ("tune", "heldout"):
        if split not in out:
            continue
        r = out[split]
        print(f"\nDetection ({split} seeds {r['seeds']}, {r['minutes_per_run'] // 1440} days each)")
        print(f"{'':22s}{'threshold-only':>18s}{'full stack':>18s}")
        for key in ("recall", "precision", "false_alerts_per_day", "median_ttd_min", "peak_alerts_10min"):
            print(f"{key:22s}{str(r['threshold'][key]):>18s}{str(r['full'][key]):>18s}")
        for kind in FAULT_KINDS:
            a, b = r["threshold"]["by_fault"][kind], r["full"]["by_fault"][kind]
            print(
                f"  {kind:20s}{a['detected']}/{a['faults']} ttd {str(a['median_ttd_min']):>6s}   "
                f"{b['detected']}/{b['faults']} ttd {str(b['median_ttd_min']):>6s}"
            )


def print_dosing(out: dict) -> None:
    for split in ("tune", "heldout"):
        r = out[split]
        print(f"\nDosing ({split} seeds {r['seeds']}, {r['days_per_run']} days each)")
        for name, s in r["strategies"].items():
            print(
                f"  {name:16s} acid {s['acid_l_per_day']:7.1f} L/d ({s['acid_change_pct']:+.1f}%)  "
                f"PAC {s['coagulant_l_per_day']:6.1f} L/d ({s['coagulant_change_pct']:+.1f}%)  "
                f"blower {s['blower_kwh_per_day']:6.1f} kWh/d ({s['blower_energy_change_pct']:+.1f}%)  "
                f"out of consent {s['out_of_consent_pct']:.2f}%"
            )


def print_assistant(out: dict) -> None:
    for mode, res in out.items():
        print(
            f"\nAssistant: {mode}"
            + (f" (live calls this run: {res.get('live_calls', 0)})" if mode == "llm_guards" else "")
        )
        for split, s in res["summary"].items():
            print(f"  {split:8s} " + ", ".join(f"{k}={v}" for k, v in s.items()))


def write_summary() -> None:
    det, dos, asst = _load("detection"), _load("dosing"), _load("assistant")
    lines = [
        "# Evaluation results",
        "",
        "Generated by `plant-ai eval all`. Numbers are read from `eval/results/*.json`.",
        "",
    ]
    if det:
        lines += ["## Detection", ""]
        for split in ("heldout", "tune"):
            r = det[split]
            lines += [
                f"**{split} seeds {r['seeds'][0]}-{r['seeds'][-1]}** ({len(r['seeds'])} runs x {r['minutes_per_run'] // 1440} days, "
                f"{r['threshold']['faults']} planted faults)",
                "",
                "| Metric | Threshold-only alarms | Alarms + sensor health + PCA |",
                "|---|---|---|",
            ]
            for key, label in (
                ("recall", "Faults detected (recall)"),
                ("precision", "Alert precision"),
                ("false_alerts_per_day", "False alerts per day"),
                ("median_ttd_min", "Median time to detect (min)"),
                ("peak_alerts_10min", "Peak annunciated alerts in 10 min"),
            ):
                lines.append(f"| {label} | {r['threshold'][key]} | {r['full'][key]} |")
            lines += [
                "",
                "| Fault | Threshold-only: detected, median TTD | Full stack: detected, median TTD |",
                "|---|---|---|",
            ]
            for kind, desc in FAULT_KINDS.items():
                a, b = r["threshold"]["by_fault"][kind], r["full"]["by_fault"][kind]
                lines.append(
                    f"| {desc} | {a['detected']}/{a['faults']}, {_m(a['median_ttd_min'])} | "
                    f"{b['detected']}/{b['faults']}, {_m(b['median_ttd_min'])} |"
                )
            missed = r["full"]["missed"]
            lines += ["", f"Faults missed by the full stack: {len(missed)}" + (f" ({missed})" if missed else ""), ""]
    if dos:
        lines += ["## Dosing", ""]
        for split in ("heldout", "tune"):
            r = dos[split]
            lines += [
                f"**{split} seeds {r['seeds'][0]}-{r['seeds'][-1]}** ({len(r['seeds'])} runs x {r['days_per_run']} days)",
                "",
                "| Strategy | Acid L/day | PAC L/day | Blower kWh/day | Time out of consent |",
                "|---|---|---|---|---|",
            ]
            for _name, s in r["strategies"].items():
                lines.append(
                    f"| {s['label']} | {s['acid_l_per_day']} ({s['acid_change_pct']:+.1f} %) | "
                    f"{s['coagulant_l_per_day']} ({s['coagulant_change_pct']:+.1f} %) | "
                    f"{s['blower_kwh_per_day']} ({s['blower_energy_change_pct']:+.1f} %) | {s['out_of_consent_pct']} % |"
                )
            lines.append("")
    if asst:
        lines += ["## Assistant", ""]
        for mode, res in asst.items():
            lines += [f"**{mode}**", "", "| Split | " + " | ".join(res["summary"]["all"].keys()) + " |"]
            lines.append("|---" * (len(res["summary"]["all"]) + 1) + "|")
            for split, s in res["summary"].items():
                lines.append(f"| {split} | " + " | ".join(str(v) for v in s.values()) + " |")
            wrong = [r for r in res["rows"] if not r["correct"]]
            lines += [
                "",
                f"Scenarios not handled correctly: {[(r['id'], r['expected'], r['primary']) for r in wrong]}",
                "",
            ]
    (RESULTS / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _m(v: float | None) -> str:
    return "-" if v is None else f"{v:g} min"
